-- Base "donantes". Correr como superusuario. Las contraseñas de los roles se asignan aparte.
create table public.donors (
  id integer generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 100),
  -- sin escala fija: los datos migrados traen más de 2 decimales y se conservan
  total numeric not null check (total >= 0),
  year text not null check (year ~ '^20[0-9]{2}$'),
  created_at timestamptz not null default now()
);

-- Lo único que se publica
create schema api;
-- Suma por persona y año. Excepción: en 2024, 29 personas tienen dos filas migradas
-- (id <= 112) con el mismo monto; el sitio siempre las contó una vez.
create view api.donantes as
select name, sum(total) as total, year
from (
  select name, year, total, min(id) as id from public.donors
  where year = '2024' and id <= 112 group by name, year, total
  union all
  select name, year, total, id from public.donors
  where not (year = '2024' and id <= 112)
) as filas
group by name, year
order by min(id);

-- Una vista con GROUP BY no es actualizable y Postgres fallaría con error 55000 (500 en la API)
-- antes de mirar permisos. Con estos disparadores responde "permiso denegado".
create function public.solo_lectura() returns trigger language plpgsql as
$$ begin raise insufficient_privilege using message = 'La lista es de solo lectura'; end $$;
create trigger solo_lectura instead of insert or update or delete on api.donantes
for each row execute function public.solo_lectura();

create role web_anon nologin;
create role authenticator login noinherit;
grant web_anon to authenticator;
grant usage on schema api to web_anon;
grant select on api.donantes to web_anon;

create role panel login;
grant usage on schema public to panel;
grant select, insert, update, delete on public.donors to panel;

revoke all on database donantes from public;
grant connect on database donantes to authenticator, panel;
alter role web_anon set statement_timeout = '3s';
